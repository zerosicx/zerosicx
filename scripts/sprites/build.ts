/**
 * Generates the sakura sprite set.
 *   npm run sprites
 *
 * Writes PNGs to public/assets/sprites/sakura/ and frame metadata to
 * src/data/sakura-sprites.ts (same shape as tilemaps.ts, so toFrameMap works).
 */
import fs from 'node:fs';
import path from 'node:path';
import { packSheet, type Canvas } from './lib.ts';
import { buildTiles } from './tiles.ts';
import { buildTree } from './tree.ts';
import { buildGlow, buildLantern, buildPetals, buildShadow } from './props.ts';

const ROOT = path.resolve(import.meta.dirname, '../..');
const OUT = path.join(ROOT, 'public/assets/sprites/sakura');
const META = path.join(ROOT, 'src/data/sakura-sprites.ts');

const sheets: Record<string, ReturnType<typeof packSheet>['meta'] & { sourceName: string }> = {};

function sheet(exportName: string, file: string, frames: Parameters<typeof packSheet>[0], columns: number) {
  const { sheet, meta } = packSheet(frames, columns);
  sheet.save(path.join(OUT, file));
  sheets[exportName] = { sourceName: file, ...meta };
}

function single(file: string, canvas: Canvas) {
  canvas.save(path.join(OUT, file));
}

sheet('SakuraTiles', 'tiles.png', buildTiles(), 8);
sheet('SakuraLantern', 'lantern.png', buildLantern(), 2);
sheet('SakuraPetals', 'petals.png', buildPetals(), 4);
single('tree.png', buildTree());
single('glow.png', buildGlow());
single('shadow.png', buildShadow());

const body = Object.entries(sheets)
  .map(([name, meta]) => `export const ${name} = ${JSON.stringify(meta, null, 2)} as const;`)
  .join('\n\n');
fs.writeFileSync(META, `// Generated by scripts/sprites/build.ts — do not edit by hand.\n\n${body}\n`);

console.log(`Wrote ${Object.keys(sheets).length} sheets + 3 images to ${path.relative(ROOT, OUT)}`);
